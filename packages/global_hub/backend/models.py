class HubMasterBookingModel(Base):
    """Authoritative Customer Booking (One-Way, Hourly, or Multi-City) with Unified Reference."""
    __tablename__ = "hub_master_bookings"

    booking_id = Column(String(64), primary_key=True, default=lambda: f"bk-{uuid.uuid4().hex[:8]}")
    booking_reference = Column(String(32), unique=True, index=True, nullable=False) # e.g. LM-20481
    trip_type = Column(String(32), default="ONE_WAY") # ONE_WAY, HOURLY, MULTI_CITY
    status = Column(String(32), default="CONFIRMED", index=True) # CONFIRMED, CHAUFFEUR_DISPATCHED, IN_PROGRESS, COMPLETED, CANCELLED
    
    # Customer / Passenger Information
    passenger_type = Column(String(16), default="MYSELF") # MYSELF, SOMEONE_ELSE
    passenger_first_name = Column(String(64), nullable=False)
    passenger_last_name = Column(String(64), nullable=False)
    passenger_email = Column(String(128), nullable=False, index=True)
    passenger_phone = Column(String(32), nullable=False)
    booker_email = Column(String(128), nullable=True)
    
    # Trip Locations & Schedule
    pickup_address = Column(String(255), nullable=False)
    dropoff_address = Column(String(255), nullable=False)
    pickup_datetime_str = Column(String(64), nullable=False)
    passengers_count = Column(Integer, default=2)
    
    # Airport & Special Service Details
    flight_number = Column(String(32), nullable=True)
    pickup_meeting_point = Column(String(128), default="JFK Airport - Arrivals (Baggage Claim)")
    child_seats_count = Column(Integer, default=0)
    special_requests = Column(Text, nullable=True)
    flight_status = Column(String(32), nullable=True) # ON_SCHEDULE, EN_ROUTE, DELAYED, LANDED, CANCELLED
    flight_delay_minutes = Column(Integer, default=0)
    flight_terminal = Column(String(32), nullable=True)
    flight_gate = Column(String(32), nullable=True)
    flight_baggage_claim = Column(String(64), nullable=True)
    flight_estimated_arrival_utc = Column(DateTime, nullable=True)
    flight_grace_period_minutes = Column(Integer, default=60)
    
    # Financial Totals (Unified Customer Charge)
    vehicle_class = Column(String(64), default="BUSINESS_CLASS")
    vehicle_model_name = Column(String(128), default="Mercedes-Benz S-Class or similar")
    base_fare_usd = Column(Numeric(10, 2), default=Decimal("125.00"))
    fees_and_taxes_usd = Column(Numeric(10, 2), default=Decimal("20.00"))
    total_amount_usd = Column(Numeric(10, 2), default=Decimal("145.00"))
    payment_method = Column(String(32), default="CARD")
    stripe_payment_intent_id = Column(String(128), nullable=True)
    
    # Sourcing & Vendor Mode
    sourcing_mode = Column(String(32), default="AUTO_ROUTED")
    assigned_vendor_id = Column(String(64), nullable=True)
    assigned_vendor_name = Column(String(128), nullable=True)
    assigned_chauffeur_name = Column(String(128), default="Alex")
    assigned_chauffeur_phone = Column(String(32), default="+1 (212) 555-0199")
    assigned_vehicle_plate = Column(String(32), default="NYC 7264")
    
    # Rate & Commercial Agreement Immutability Snapshots (Section 5)
    rate_card_snapshot_json = Column(Text, nullable=True)
    commercial_terms_snapshot_json = Column(Text, nullable=True)
    
    # Timestamp Tracking
    pickup_datetime_utc = Column(DateTime, nullable=False, default=lambda: datetime.now(timezone.utc))
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), index=True)
    updated_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), onupdate=lambda: datetime.now(timezone.utc))

    legs = relationship("HubLegModel", back_populates="booking", cascade="all, delete-orphan")
    invoice = relationship("HubInvoiceModel", uselist=False, back_populates="booking", cascade="all, delete-orphan")
    settlement = relationship("HubEscrowSettlementModel", uselist=False, back_populates="booking", cascade="all, delete-orphan")
    telemetry = relationship("HubDriverTelemetryModel", uselist=False, back_populates="booking", cascade="all, delete-orphan")


